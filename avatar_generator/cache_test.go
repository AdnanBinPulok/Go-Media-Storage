func TestCacheConcurrent(t *testing.T) {
	c := NewCache(CacheConfig{TTL: time.Minute, MaxItems: 32})

	const workers = 8
	const perWorker = 12

	var wg sync.WaitGroup
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func(w int) {
			defer wg.Done()
			for i := 0; i < perWorker; i++ {
				id := testIDs[(w+i)%len(testIDs)]
				if _, _, err := c.PNG(id, 64, DefaultPaddingPct); err != nil {
					t.Errorf("concurrent PNG: %v", err)
					return
				}
				_ = c.Stats()
			}
		}(w)
	}
	wg.Wait()

	if c.Len() > 32 {
		t.Errorf("Len() = %d, above MaxItems", c.Len())
	}
}

