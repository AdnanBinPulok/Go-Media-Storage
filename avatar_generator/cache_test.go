func TestCacheHitAndMiss(t *testing.T) {
	c := NewCache(CacheConfig{TTL: time.Minute, MaxItems: 100})

	first, hit, err := c.PNG("cache-me", 128, DefaultPaddingPct)
	if err != nil {
		t.Fatalf("first call: %v", err)
	}
	if hit {
		t.Error("first call reported a cache hit")
	}

	second, hit, err := c.PNG("cache-me", 128, DefaultPaddingPct)
	if err != nil {
		t.Fatalf("second call: %v", err)
	}
	if !hit {
		t.Error("second call reported a miss")
	}
	if !bytes.Equal(first, second) {
		t.Error("cached bytes differ from the generated bytes")
	}

	stats := c.Stats()
	if stats.Items != 1 || stats.Hits != 1 || stats.Misses != 1 {
		t.Errorf("stats = %+v, want 1 item / 1 hit / 1 miss", stats)
	}
}

func TestCacheKeyCoversAllInputs(t *testing.T) {
	c := NewCache(CacheConfig{TTL: time.Minute, MaxItems: 100})

	base := mustPNG(t, "key-test", 128, 0.05)
	c.PNG("key-test", 128, 0.05)

	// Every input that changes pixels must produce a separate key.
	cases := []struct {
		name    string
		size    int
		padding float64
		want    []byte
	}{
		{"different size", 256, 0.05, mustPNG(t, "key-test", 256, 0.05)},
		{"different padding", 128, 0.10, mustPNG(t, "key-test", 128, 0.10)},
	}

	for _, tc := range cases {
		got, hit, err := c.PNG("key-test", tc.size, tc.padding)
		if err != nil {
			t.Fatalf("%s: %v", tc.name, err)
		}
		if hit {
			t.Errorf("%s: unexpected cache hit", tc.name)
		}
		if !bytes.Equal(got, tc.want) {
			t.Errorf("%s: wrong avatar returned", tc.name)
		}
	}

	// Clamped-equivalent requests must share one entry.
	if _, hit, _ := c.PNG("key-test", 128, 0.0500000001); !hit {
		t.Error("equivalent padding produced a cache miss")
	}
	_ = base
}

func TestCacheLRUEviction(t *testing.T) {
	c := NewCache(CacheConfig{TTL: time.Minute, MaxItems: 2})

	c.PNG("a", 64, DefaultPaddingPct)
	c.PNG("b", 64, DefaultPaddingPct)

	// Touch "a" so "b" becomes the eviction candidate.
	if _, hit, _ := c.PNG("a", 64, DefaultPaddingPct); !hit {
		t.Fatal("expected a hit for a")
	}

	c.PNG("c", 64, DefaultPaddingPct)

	if c.Len() != 2 {
		t.Fatalf("Len() = %d, want 2", c.Len())
	}

	if _, hit, _ := c.PNG("a", 64, DefaultPaddingPct); !hit {
		t.Error("recently used entry was evicted")
	}
	if _, hit, _ := c.PNG("b", 64, DefaultPaddingPct); hit {
		t.Error("least recently used entry was not evicted")
	}
}

func TestCacheTTL(t *testing.T) {
	c := NewCache(CacheConfig{TTL: 25 * time.Millisecond, MaxItems: 10})

	c.PNG("ttl", 64, DefaultPaddingPct)
	if _, hit, _ := c.PNG("ttl", 64, DefaultPaddingPct); !hit {
		t.Fatal("expected a hit before expiry")
	}

	time.Sleep(50 * time.Millisecond)

	if _, hit, _ := c.PNG("ttl", 64, DefaultPaddingPct); hit {
		t.Error("entry did not expire after TTL")
	}
	if c.Len() != 1 {
		t.Errorf("expired entry was not replaced, Len() = %d", c.Len())
	}
}

func TestCacheByteCap(t *testing.T) {
	one := mustPNG(t, "bytes", 256, DefaultPaddingPct)

	// Room for exactly one entry.
	c := NewCache(CacheConfig{TTL: time.Minute, MaxItems: 1000, MaxBytes: int64(len(one)) + 8})

	c.PNG("bytes", 256, DefaultPaddingPct)
	c.PNG("bytes-2", 256, DefaultPaddingPct)

	if c.Len() != 1 {
		t.Errorf("Len() = %d, want 1 after byte-cap eviction", c.Len())
	}
	stats := c.Stats()
	if stats.Bytes > int64(len(one))+8 {
		t.Errorf("Bytes = %d, above the configured cap", stats.Bytes)
	}
	if stats.Evictions == 0 {
		t.Error("no eviction recorded")
	}
}

func TestCachePurge(t *testing.T) {
	c := NewCache(CacheConfig{TTL: time.Minute, MaxItems: 10})

	c.PNG("purge-1", 64, DefaultPaddingPct)
	c.PNG("purge-1", 64, DefaultPaddingPct)
	c.Purge()

	if c.Len() != 0 {
		t.Errorf("Len() = %d after Purge, want 0", c.Len())
	}
	if s := c.Stats(); s.Hits != 0 || s.Misses != 0 || s.Bytes != 0 {
		t.Errorf("Stats() = %+v after Purge, want zeroed", s)
	}
}

func TestNilCacheIsUsable(t *testing.T) {
	var c *Cache

	png, hit, err := c.PNG("nil-cache", 64, DefaultPaddingPct)
	if err != nil {
		t.Fatalf("nil cache: %v", err)
	}
	if hit {
		t.Error("nil cache reported a hit")
	}
	if !bytes.Equal(png, mustPNG(t, "nil-cache", 64, DefaultPaddingPct)) {
		t.Error("nil cache returned different bytes than the generator")
	}
	if c.Len() != 0 || c.Stats() != (Stats{}) {
		t.Error("nil cache returned non-zero state")
	}
	c.Purge() // must not panic
}

